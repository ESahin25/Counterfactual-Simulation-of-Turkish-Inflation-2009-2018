def _fetch_evds(evds, series, start=START_DATE, end=END_DATE, frequency=None):
    """Convenience wrapper: EVDS returns pandas, we want polars."""
    kwargs = {"startdate": start, "enddate": end}
    if frequency is not None:
        kwargs["frequency"] = frequency
    pdf = evds.get_data(series, **kwargs)
    return pl.from_pandas(pdf)


def fetch_evds_series(evds):
    """Fetch all EVDS data and save to parquet."""
    print("Fetching CPI main groups...")
    _fetch_evds(evds, CPI_MAIN).write_parquet(DATA_DIR / "cpi_main.parquet")

    print("Fetching CPI sub-indices...")
    _fetch_evds(evds, CPI_SUB).write_parquet(DATA_DIR / "cpi_sub.parquet")

    print("Fetching CPI special coverage measures...")
    _fetch_evds(evds, CPI_SPECIAL).write_parquet(DATA_DIR / "cpi_special.parquet")

    print("Fetching import unit value index...")
    _fetch_evds(evds, ["TP.DT.IT.FIY.D01.2010"]).write_parquet(DATA_DIR / "import_uvi.parquet")

    print("Fetching CBRT funding and late-liquidity rates...")
    _fetch_evds(evds, ["TP.APIFON4", "TP.PY.P02.LON"]).write_parquet(DATA_DIR / "rates.parquet")

    # USD/TRY at monthly frequency (frequency=5 in EVDS API)
    print("Fetching USD/TRY (monthly)...")
    _fetch_evds(evds, ["TP.DK.USD.A.YTL"], frequency=5).write_parquet(DATA_DIR / "fx.parquet")


def build_policy_rate():
    """Expand discrete CBRT overnight borrowing decisions to a monthly series."""
    df_on = pl.DataFrame({
        "date": [r[0] for r in ON_DECISIONS],
        "overnight_borrowing": [r[1] for r in ON_DECISIONS],
    }).with_columns(pl.col("date").str.to_date("%Y-%m-%d"))

    monthly_dates = pl.date_range(
        date(2002, 2, 1), date(2026, 3, 1), interval="1mo", eager=True
    )
    df_monthly = pl.DataFrame({"month": monthly_dates})

    df_on = df_on.with_columns(pl.col("date").dt.truncate("1mo").alias("month"))
    df_on_monthly = df_on.group_by("month").agg(pl.col("overnight_borrowing").last()).sort("month")

    df_policy = (
        df_monthly
        .join(df_on_monthly, on="month", how="left")
        .with_columns(pl.col("overnight_borrowing").forward_fill())
        .filter(pl.col("month") >= date(2003, 1, 1))
    )
    df_policy.write_parquet(DATA_DIR / "policy_rate.parquet")
    print(f"Policy rate: {df_policy.shape[0]} months written")


def build_ipi():
    """Save the embedded TÜİK seasonally-adjusted IPI to parquet."""
    df_ipi = pl.DataFrame({
        "Tarih": list(IPI_DATA.keys()),
        "ipi": list(IPI_DATA.values()),
    })
    df_ipi.write_parquet(DATA_DIR / "ipi.parquet")
    print(f"IPI: {df_ipi.shape[0]} months written")


def fetch_commodity_index():
    """IMF All Commodity Price Index (non-fuel included) via FRED's public CSV endpoint."""
    print("Fetching IMF commodity index from FRED...")
    url = "https://fred.stlouisfed.org/graph/fredgraph.csv?id=PALLFNFINDEXM"
    df = pd.read_csv(url)
    # Newer FRED CSVs label the date column "observation_date"; older ones used "DATE".
    date_col = "observation_date" if "observation_date" in df.columns else "DATE"
    df = df.rename(columns={date_col: "DATE"})
    df["DATE"] = pd.to_datetime(df["DATE"])
    df = df[(df["DATE"] >= "2002-01-01") & (df["DATE"] <= "2026-04-01")].dropna()
    pl.from_pandas(df).write_parquet(DATA_DIR / "PALLFNFINDEXM.parquet")


def run():
    """Orchestrate the data collection stage."""
    evds = evdsAPI(EVDS_API_KEY)
    fetch_evds_series(evds)
    build_policy_rate()
    build_ipi()
    fetch_commodity_index()
    print("Stage 0 complete: data collection done.")


if __name__ == "__main__":
    run()
